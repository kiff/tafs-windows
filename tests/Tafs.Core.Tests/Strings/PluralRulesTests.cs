using Tafs.Core.Words;

namespace Tafs.Core.Tests.Strings;

[Part("strings")]
public class PluralRulesTests
{
    [Theory]
    [InlineData("en", 0, "other")]
    [InlineData("en", 1, "one")]
    [InlineData("en", 2, "other")]
    [InlineData("de", 1, "one")]
    [InlineData("nl", 5, "other")]
    [InlineData("es", 1, "one")]
    [InlineData("it", 1, "one")]
    [InlineData("fr", 0, "one")]
    [InlineData("fr", 1, "one")]
    [InlineData("fr", 2, "other")]
    [InlineData("pt", 0, "other")]
    [InlineData("pt", 1, "one")]
    [InlineData("pt", 2, "other")]
    [InlineData("pl", 0, "many")]
    [InlineData("pl", 1, "one")]
    [InlineData("pl", 2, "few")]
    [InlineData("pl", 4, "few")]
    [InlineData("pl", 5, "many")]
    [InlineData("pl", 12, "many")]
    [InlineData("pl", 14, "many")]
    [InlineData("pl", 22, "few")]
    [InlineData("pl", 100, "many")]
    [InlineData("pl", 102, "few")]
    [InlineData("pl", -3, "few")]
    // CLDR's whole-number rules for the languages since the first eight.
    [InlineData("pt-BR", 0, "one")]
    [InlineData("hy", 0, "one")]
    [InlineData("bn", 1, "one")]
    [InlineData("bn", 2, "other")]
    [InlineData("ja", 1, "other")]
    [InlineData("zh-Hant", 1, "other")]
    [InlineData("cs", 1, "one")]
    [InlineData("cs", 4, "few")]
    [InlineData("cs", 5, "other")]
    [InlineData("sk", 22, "other")]
    [InlineData("lt", 1, "one")]
    [InlineData("lt", 11, "other")]
    [InlineData("lt", 21, "one")]
    [InlineData("lt", 9, "few")]
    [InlineData("lt", 10, "other")]
    [InlineData("lv", 0, "zero")]
    [InlineData("lv", 1, "one")]
    [InlineData("lv", 11, "zero")]
    [InlineData("lv", 21, "one")]
    [InlineData("lv", 22, "other")]
    [InlineData("sl", 1, "one")]
    [InlineData("sl", 102, "two")]
    [InlineData("sl", 3, "few")]
    [InlineData("sl", 5, "other")]
    [InlineData("ro", 0, "few")]
    [InlineData("ro", 1, "one")]
    [InlineData("ro", 19, "few")]
    [InlineData("ro", 20, "other")]
    [InlineData("ro", 101, "few")]
    [InlineData("hr", 21, "one")]
    [InlineData("hr", 11, "other")]
    [InlineData("sr-Latn", 3, "few")]
    [InlineData("sr-Latn", 13, "other")]
    [InlineData("mk", 21, "one")]
    [InlineData("mk", 11, "other")]
    [InlineData("he", 2, "two")]
    [InlineData("he", 20, "other")]
    [InlineData("ar", 0, "zero")]
    [InlineData("ar", 2, "two")]
    [InlineData("ar", 3, "few")]
    [InlineData("ar", 103, "few")]
    [InlineData("ar", 11, "many")]
    [InlineData("ar", 100, "other")]
    [InlineData("ar", 102, "other")]
    public void A_number_takes_the_form_its_language_gives_it(string language, long count, string form) =>
        Assert.Equal(form, PluralRules.Form(language, count));

    [Fact]
    public void An_unknown_language_has_no_rule() =>
        Assert.Throws<ArgumentException>(() => PluralRules.Form("xx", 1));
}
